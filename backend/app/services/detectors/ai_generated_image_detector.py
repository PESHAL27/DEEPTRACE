"""
DEEPTRACE - Whole-Image AI-Generated Image Detector Service
===========================================================
Integrates the open-source Smaug-AI-Image-Detector (Abacus.AI, Apache 2.0)
for whole-image synthetic / generative image identification across all categories:
- Human faces and portraits
- Landscapes and nature
- Architecture and buildings
- Commercial photography and products
- Digital artwork, illustrations, and paintings

Architecture & Preprocessing Contract:
- Base: Vision-only EmbeddingGemma-2 (439M parameters, vision-streamlined)
- Preprocessing: Native Smaug views (shorter side -> 576, 528x528 crops, 140 soft tokens)
- Output Semantics: Sigmoid probability in [0.0, 1.0] representing model likelihood
  that the image is synthetically generated by an AI model.
- Execution: Cached singleton, thread-safe, CPU / GPU inference with fallback.
"""

import math
import os
import sys
import time
import threading
from pathlib import Path
from typing import Optional, Union, List, Dict, Any

import numpy as np
import torch
from PIL import Image, ImageOps, UnidentifiedImageError

from ...models.schemas import AIGenerationResult
from ...utils.logger import logger
from ...utils.file_utils import sanitize_error_message

# Resolve paths
MODULE_PATH = Path(__file__).resolve()
BACKEND_DIR = MODULE_PATH.parents[3]
LOCAL_WEIGHTS_DIR = BACKEND_DIR / "weights" / "smaug"
ALT_WEIGHTS_DIR = MODULE_PATH.parents[2] / "weights" / "smaug"
HF_MODEL_ID = "abacusai/Smaug-AI-Image-Detector"

# Thread safety lock
_smaug_lock = threading.Lock()
_cached_detector: Optional[Any] = None
_load_error: Optional[str] = None
_is_initialized: bool = False
_device_used: str = "cpu"

PROVISIONAL_AI_THRESHOLD = 0.50
BORDERLINE_MARGIN = 0.05  # Scores in [0.45, 0.55] flagged as borderline


def get_model_directory() -> Path:
    """Returns local model weights directory if present, otherwise returns weights directory."""
    if LOCAL_WEIGHTS_DIR.exists() and (LOCAL_WEIGHTS_DIR / "config.json").exists():
        return LOCAL_WEIGHTS_DIR
    if ALT_WEIGHTS_DIR.exists() and (ALT_WEIGHTS_DIR / "config.json").exists():
        return ALT_WEIGHTS_DIR
    return LOCAL_WEIGHTS_DIR


def get_smaug_detector(force_device: Optional[str] = None) -> Any:
    """
    Retrieves or initializes the cached SmaugImageDetect instance.
    Guarantees thread-safe singleton loading and cached memory persistence.
    """
    global _cached_detector, _is_initialized, _load_error, _device_used

    with _smaug_lock:
        if _is_initialized and _cached_detector is not None:
            return _cached_detector

        # Check weights directory
        weights_dir = get_model_directory()
        if not weights_dir.exists() or not (weights_dir / "config.json").exists():
            # If not yet downloaded locally, attempt snapshot_download with local_dir to avoid symlink issues
            logger.info(f"Local Smaug weights not found in {weights_dir}. Fetching checkpoint...")
            weights_dir.mkdir(parents=True, exist_ok=True)
            try:
                from huggingface_hub import snapshot_download
                snapshot_download(
                    HF_MODEL_ID,
                    local_dir=str(weights_dir),
                    local_dir_use_symlinks=False
                )
            except Exception as e:
                _load_error = f"Failed to download Smaug checkpoint: {sanitize_error_message(str(e))}"
                logger.error(_load_error)
                raise RuntimeError(_load_error)

        # Import smaug_image_detect from local directory
        weights_str = str(weights_dir)
        if weights_str not in sys.path:
            sys.path.insert(0, weights_str)

        try:
            from smaug_image_detect import SmaugImageDetect
        except ImportError as e:
            _load_error = f"Failed to import smaug_image_detect: {sanitize_error_message(str(e))}"
            logger.error(_load_error)
            raise RuntimeError(_load_error)

        # Determine target device
        if force_device:
            target_device = force_device
        elif torch.cuda.is_available():
            target_device = "cuda"
        else:
            target_device = "cpu"

        logger.info(f"Initializing Smaug AI Image Detector on device: {target_device}...")
        start_t = time.perf_counter()

        try:
            detector = SmaugImageDetect.from_pretrained(weights_str, device=target_device)
            elapsed_s = time.perf_counter() - start_t
            logger.info(f"Smaug AI Image Detector initialized successfully in {elapsed_s:.2f}s on {target_device}.")
            _cached_detector = detector
            _device_used = target_device
            _is_initialized = True
            _load_error = None
            return _cached_detector
        except Exception as e:
            if target_device == "cuda":
                logger.warning(f"CUDA initialization failed ({e}); retrying on CPU fallback...")
                try:
                    detector = SmaugImageDetect.from_pretrained(weights_str, device="cpu")
                    _cached_detector = detector
                    _device_used = "cpu"
                    _is_initialized = True
                    _load_error = None
                    return _cached_detector
                except Exception as cpu_e:
                    _load_error = f"Smaug detector CPU fallback failed: {sanitize_error_message(str(cpu_e))}"
                    logger.error(_load_error)
                    raise RuntimeError(_load_error)
            else:
                _load_error = f"Smaug detector initialization failed: {sanitize_error_message(str(e))}"
                logger.error(_load_error)
                raise RuntimeError(_load_error)


def validate_and_open_image(image_input: Union[str, Path, Image.Image, np.ndarray]) -> Image.Image:
    """
    Validates image file existence, format, and decodability.
    Converts numpy arrays, file paths, or PIL Images to a clean RGB PIL Image.
    Raises ValueError on corrupt, unreadable, or missing inputs.
    """
    if isinstance(image_input, Image.Image):
        return ImageOps.exif_transpose(image_input).convert("RGB")

    if isinstance(image_input, np.ndarray):
        if image_input.size == 0:
            raise ValueError("Empty image array provided.")
        # If 3-channel numpy array, assume BGR from OpenCV and convert to RGB
        if len(image_input.shape) == 3 and image_input.shape[2] == 3:
            import cv2
            rgb = cv2.cvtColor(image_input, cv2.COLOR_BGR2RGB)
            return Image.fromarray(rgb)
        return Image.fromarray(image_input).convert("RGB")

    path = Path(image_input)
    if not path.exists():
        raise ValueError(f"Image evidence file not found: {path}")

    # Validate extension
    allowed = {".jpg", ".jpeg", ".png", ".webp"}
    if path.suffix.lower() not in allowed:
        raise ValueError(f"Unsupported image extension '{path.suffix}'. Supported: {', '.join(sorted(allowed))}")

    try:
        with Image.open(path) as img:
            img.verify()
        # Re-open after verify() to load content
        with Image.open(path) as img:
            return ImageOps.exif_transpose(img).convert("RGB")
    except (UnidentifiedImageError, OSError, ValueError) as e:
        raise ValueError(f"Corrupt or unreadable image file: {sanitize_error_message(str(e))}")


def detect_ai_generated_image(
    image_input: Union[str, Path, Image.Image, np.ndarray],
    crops: int = 1,
    threshold: float = PROVISIONAL_AI_THRESHOLD,
    force_device: Optional[str] = None
) -> AIGenerationResult:
    """
    Executes whole-image AI-generation detection on the input evidence.
    
    Args:
        image_input: Path, PIL Image, or numpy array.
        crops: Number of crops evaluated (1 for center-crop fast inference, 3 for multi-crop).
        threshold: Decision boundary (default 0.50).
        force_device: Optional device override ('cpu' or 'cuda').
        
    Returns:
        AIGenerationResult schema with raw model score, cautious assessment, and metadata.
    """
    start_t = time.perf_counter()

    # 1. Input image validation
    try:
        pil_img = validate_and_open_image(image_input)
    except Exception as e:
        elapsed_ms = round((time.perf_counter() - start_t) * 1000, 2)
        logger.warning(f"Whole-image detector rejected invalid image: {e}")
        return AIGenerationResult(
            model_name="Smaug AI Image Detector",
            model_id=HF_MODEL_ID,
            score=None,
            predicted_label="inconclusive",
            assessment="Analysis unavailable",
            confidence=None,
            threshold=threshold,
            crops_evaluated=crops,
            device=_device_used,
            status="error",
            error_message=sanitize_error_message(str(e)),
            execution_time_ms=elapsed_ms
        )

    # 2. Model retrieval
    try:
        detector = get_smaug_detector(force_device=force_device)
    except Exception as e:
        elapsed_ms = round((time.perf_counter() - start_t) * 1000, 2)
        logger.error(f"Smaug detector unavailable: {e}")
        return AIGenerationResult(
            model_name="Smaug AI Image Detector",
            model_id=HF_MODEL_ID,
            score=None,
            predicted_label="inconclusive",
            assessment="Analysis unavailable",
            confidence=None,
            threshold=threshold,
            crops_evaluated=crops,
            device=_device_used,
            status="unavailable",
            error_message=sanitize_error_message(str(e)),
            execution_time_ms=elapsed_ms
        )

    # 3. Model inference
    try:
        with torch.inference_mode():
            # detector accepts PIL image or list of images
            score = detector(pil_img, crops=crops)
            raw_score = float(score)

        elapsed_ms = round((time.perf_counter() - start_t) * 1000, 2)

        # 4. Score interpretation and cautious assessment
        # Score is continuous probability in [0.0, 1.0] that image is AI-generated
        is_borderline = abs(raw_score - threshold) <= BORDERLINE_MARGIN

        if raw_score >= threshold:
            predicted_label = "likely_ai_generated"
            assessment = "Likely AI-generated"
            confidence = raw_score
        else:
            predicted_label = "likely_camera_captured"
            assessment = "Likely camera-captured"
            confidence = round(1.0 - raw_score, 4)

        logger.info(
            f"[Smaug Forensic Diagnostic] Model: Smaug-AI-Image-Detector | "
            f"Raw Score: {raw_score:.4f} | Label: {predicted_label} | "
            f"Assessment: '{assessment}' | Threshold: {threshold:.2f} | "
            f"Borderline: {is_borderline} | Time: {elapsed_ms}ms"
        )

        return AIGenerationResult(
            model_name="Smaug AI Image Detector",
            model_id=HF_MODEL_ID,
            score=round(raw_score, 4),
            predicted_label=predicted_label,
            assessment=assessment,
            confidence=round(confidence, 4),
            threshold=threshold,
            crops_evaluated=crops,
            device=_device_used,
            status="completed",
            error_message=None,
            execution_time_ms=elapsed_ms
        )

    except torch.cuda.OutOfMemoryError as e:
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
        elapsed_ms = round((time.perf_counter() - start_t) * 1000, 2)
        logger.error(f"CUDA Out of Memory during Smaug inference: {e}")
        return AIGenerationResult(
            model_name="Smaug AI Image Detector",
            model_id=HF_MODEL_ID,
            score=None,
            predicted_label="inconclusive",
            assessment="Analysis unavailable",
            confidence=None,
            threshold=threshold,
            crops_evaluated=crops,
            device=_device_used,
            status="error",
            error_message="GPU out of memory during whole-image AI detection.",
            execution_time_ms=elapsed_ms
        )
    except Exception as e:
        elapsed_ms = round((time.perf_counter() - start_t) * 1000, 2)
        clean_err = sanitize_error_message(str(e))
        logger.error(f"Smaug inference execution failure: {clean_err}", exc_info=True)
        return AIGenerationResult(
            model_name="Smaug AI Image Detector",
            model_id=HF_MODEL_ID,
            score=None,
            predicted_label="inconclusive",
            assessment="Analysis unavailable",
            confidence=None,
            threshold=threshold,
            crops_evaluated=crops,
            device=_device_used,
            status="error",
            error_message=f"Model inference failed: {clean_err}",
            execution_time_ms=elapsed_ms
        )
